# ###### ВИЗНАЧЕННЯ ТЕМАТИЧНОЇ НАЛЕЖНОСТІ НОВИНИ ДО ОХОРОНИ ПРАЦІ / ОПРЕДЕЛЕНИЕ ТЕМАТИЧЕСКОЙ ПРИНАДЛЕЖНОСТИ НОВОСТИ К ОХРАНЕ ТРУДА ######
def is_occupational_safety_related_feed_entry(feed_entry: RssFeedEntry) -> bool:
    """Повертає True, якщо RSS/Atom-матеріал тематично стосується охорони праці.
    Возвращает True, если RSS/Atom-материал тематически относится к охране труда.
    """

    search_text = " ".join(
        value.strip()
        for value in (
            feed_entry.title_text,
            feed_entry.summary_text,
            feed_entry.link_url,
        )
        if value.strip()
    ).lower()
    search_text = search_text.replace("ё", "е").replace("’", "'").replace("`", "'")
    search_text = re.sub(r"[^0-9a-zа-яіїєґ']+", " ", search_text, flags=re.IGNORECASE)

    if any(phrase in search_text for phrase in _DIRECT_OCCUPATIONAL_SAFETY_PHRASES):
        return True
    return any(stem in search_text for stem in _TOPIC_STEMS) and any(
        stem in search_text for stem in _WORK_CONTEXT_STEMS
    )
